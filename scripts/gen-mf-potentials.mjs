#!/usr/bin/env node
/**
 * Regenerates src/features/tools/mystic-frontier/potentialsData.ts (the Mystic Frontier
 * potential line list) from the WZ familiar-potentials manifest.
 *
 * Usage:
 *   node scripts/gen-mf-potentials.mjs manifests/v271/familiar-potentials.json
 *
 * Mystic Frontier lines live in ids 110001-153303: the second digit is the rarity
 * (1 common .. 5 legendary). The manifest also flags them `mf: true`, but the flag has
 * been wrong before (v271's count-based "for each" lines were first flagged false), so
 * the id range is the selector and the flag is only cross-checked: any disagreement fails
 * the run so the manifest gets fixed rather than silently trusted either way.
 *
 * The 2xxxxx `mf` entries are the bonus dice and stopwatch effects, which live in
 * bonusItemsData.ts (hand-maintained; their values are not in item.json) and are skipped.
 *
 * `template` is the raw effect string with #placeholders and `params` its magnitudes.
 * potentialEngine.ts interprets both; a new condition wording needs a matcher there or
 * the line shows in the picker but never scores.
 */

import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const manifestPath = process.argv[2];
if (!manifestPath) {
  console.error("Usage: node scripts/gen-mf-potentials.mjs <path/to/familiar-potentials.json>");
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(resolve(manifestPath), "utf8"));
const entries = manifest.entries ?? manifest;

const RARITY_BY_DIGIT = { 1: "common", 2: "rare", 3: "epic", 4: "unique", 5: "legendary" };
const MF_ID = /^1[1-5]\d{4}$/;
// The magnitudes the templates reference. `level` also carries bookkeeping keys on some
// event lines (linkOptionMF) that are not #placeholders, so only these are emitted.
const PARAM_KEYS = ["add", "sub", "mul", "w", "x"];

function magnitudes(level) {
  return Object.fromEntries(PARAM_KEYS.filter((k) => k in level).map((k) => [k, level[k]]));
}

const lines = [];
const problems = [];
for (const [id, entry] of Object.entries(entries)) {
  const inRange = MF_ID.test(id);
  if (!inRange && entry.mf && !/^2\d{5}$/.test(id)) {
    problems.push(`${id} is flagged mf but is outside the 11xxxx-15xxxx and 2xxxxx ranges`);
  }
  if (!inRange) continue;
  if (!entry.mf) problems.push(`${id} is in the Mystic Frontier id range but flagged mf: false`);
  const rarity = RARITY_BY_DIGIT[id[1]];
  lines.push(`  { id: ${Number(id)}, rarity: "${rarity}", template: ${JSON.stringify(entry.string)}, params: ${JSON.stringify(magnitudes(entry.level))} },`);
}
if (problems.length) {
  console.error(`Manifest disagrees with the id-range rule on ${problems.length} entries:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}
lines.sort((a, b) => Number(a.match(/id: (\d+)/)[1]) - Number(b.match(/id: (\d+)/)[1]));

const manifestRel = manifestPath.replace(/\\/g, "/").replace(/^.*?(manifests\/)/, "$1");
const out = [
  `// AUTO-GENERATED by scripts/gen-mf-potentials.mjs from ${manifestRel} (ids 110001-153303).`,
  "// Mystic Frontier familiar potential lines. `template` is the raw effect string with",
  "// #placeholders; `params` supplies the magnitudes (add/sub -> flat, mul -> multiplier,",
  "// w -> threshold, x -> roll-chance %). See potentialEngine.ts for interpretation.",
  "",
  "// `rarity`/`params` are deliberately widened (plain `string` / index signature). With",
  "// a literal-union `rarity` or optional-keys `params`, TypeScript keeps each of the 1.7k",
  "// array elements as a distinct literal type and forms a union that overflows",
  '// ("union too complex"). Plain field types let every element collapse to one type.',
  "// Consumers narrow `rarity` back to MfRarity (it always holds one of those values).",
  "export interface MfPotentialDef {",
  "  id: number;",
  "  rarity: string;",
  "  template: string;",
  "  params: Readonly<Record<string, number>>;",
  "}",
  "",
  "export const MF_POTENTIALS: readonly MfPotentialDef[] = [",
  ...lines,
  "];",
  "",
].join("\n");

writeFileSync(resolve("src/features/tools/mystic-frontier/potentialsData.ts"), out);
console.log(`Written ${lines.length} Mystic Frontier potentials to potentialsData.ts`);
