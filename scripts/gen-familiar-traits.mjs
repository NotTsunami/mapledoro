#!/usr/bin/env node
/**
 * Regenerates src/features/tools/mystic-frontier/familiarTraits.ts (familiar id -> [type, element])
 * from the WZ familiar manifest.
 *
 * Usage:
 *   node scripts/gen-familiar-traits.mjs manifests/v271/familiar.json
 *
 * The familiar list itself (names, sprites, card ids) is regenerated separately by
 * gen-familiars.mjs into the character setup flow's familiarsData.ts; Mystic Frontier's
 * familiars.ts joins the two by id, so run both on a version bump or the newest familiars
 * silently drop out of the Mystic Frontier picker.
 *
 * Manifest familiar types are normalized to Mystic Frontier wording (matching its potential
 * condition text): Fish -> Aquatic, Nymph -> Fairy, Machine -> Mechanical. Any other type or
 * element outside the MfType / MfElement unions in types.ts fails the run rather than emitting
 * a value the app can't type.
 */

import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const manifestPath = process.argv[2];
if (!manifestPath) {
  console.error("Usage: node scripts/gen-familiar-traits.mjs <path/to/familiar.json>");
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(resolve(manifestPath), "utf8"));
const entries = manifest.entries ?? manifest;

const TYPE_ALIASES = { Fish: "Aquatic", Nymph: "Fairy", Machine: "Mechanical" };
const MF_TYPES = new Set(["Human", "Beast", "Plant", "Aquatic", "Fairy", "Reptile", "Devil", "Undead", "Mechanical"]);
const MF_ELEMENTS = new Set(["None", "Fire", "Ice", "Lightning", "Poison", "Dark", "Holy"]);

const lines = [];
const problems = [];
for (const [id, entry] of Object.entries(entries)) {
  const type = TYPE_ALIASES[entry.familiarType] ?? entry.familiarType;
  const element = entry.element;
  if (!MF_TYPES.has(type) || !MF_ELEMENTS.has(element)) {
    problems.push(`${id} (${entry.name}): type=${entry.familiarType} element=${element}`);
    continue;
  }
  lines.push(`  ${id}: ["${type}", "${element}"],`);
}
if (problems.length) {
  console.error(`Unrecognized type/element on ${problems.length} entries:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

const manifestRel = manifestPath.replace(/\\/g, "/").replace(/^.*?(manifests\/)/, "$1");
const out = [
  `// AUTO-GENERATED by scripts/gen-familiar-traits.mjs from ${manifestRel}. Do not edit by hand.`,
  "// Maps familiar id -> [type, element]. Type labels normalized to Mystic Frontier",
  "// wording (Fish->Aquatic, Nymph->Fairy, Machine->Mechanical).",
  "",
  'import type { MfElement, MfType } from "./types";',
  "",
  "export const FAMILIAR_TRAITS: Readonly<Record<number, readonly [MfType, MfElement]>> = {",
  ...lines,
  "};",
  "",
].join("\n");

const targetPath = resolve("src/features/tools/mystic-frontier/familiarTraits.ts");
writeFileSync(targetPath, out);
console.log(`Written ${lines.length} familiar traits to familiarTraits.ts`);
